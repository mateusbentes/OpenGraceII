//! The Vulkan backend's SPIR-V build script.
//!
//! The library's GLSL 450 sources are compiled per shader by glslangValidator
//! (the build-time prerequisite, decision 44) and the generated header
//! carries the per-shader byte arrays. The backend's pipeline resolves
//! through the same enum order as the library. The build script runs only
//! when the `vulkan` feature is enabled.
//!
//! When the validator is not on the build machine's PATH (the macOS and
//! the iOS builds, where the Vulkan backend only compiles and never
//! runs), the script falls back to the committed SPIR-V arrays
//! (vulkan_spirv_committed.rs, generated on the Linux validation
//! machine) and the library compiles unchanged. When the validator is
//! present the script recompiles and the committed arrays are nothing
//! more than the fallback's source.

use std::env;
use std::fs;
use std::process::Command;

fn main() {
    // The build's cfgs are registered so the compiler's unexpected-cfg
    // lint stays quiet (the standard custom-cfg registration).
    println!("cargo::rustc-check-cfg=cfg(spirv_generated)");
    println!("cargo::rustc-check-cfg=cfg(spirv_fallback)");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/render/vulkan/shader_library.rs");
    println!("cargo:rerun-if-changed=src/render/vulkan/vulkan_spirv_committed.rs");
    if env::var("CARGO_FEATURE_VULKAN").is_err() {
        return;
    }
    let out_dir = env::var("OUT_DIR").unwrap();
    let manifest = env::var("CARGO_MANIFEST_DIR").unwrap();
    let library = format!(
        "{}/src/render/vulkan/shader_library.rs",
        manifest
    );
    let source = fs::read_to_string(&library).expect(
        "the Vulkan shader library must exist",
    );
    let shaders = extract_shaders(&source);

    // The validator's presence decides the path: with it the library's
    // sources recompile per build; without it the committed arrays are
    // the build's input (the macOS and the iOS builds where the backend
    // only compiles and never runs).
    let validator = find_validator();
    if let Some(validator) = validator {
        let mut generated = String::from(
            "// Generated by core/build.rs from the shader library's GLSL 450\n\
             // sources. Do not edit: change the library and rebuild.\n\n",
        );
        for (name, body) in &shaders {
            let spv = compile_shader(&out_dir, name, body, &validator);
            let spv_path = format!("{}/{}.spv", out_dir, name);
            fs::write(&spv_path, &spv).expect("the SPIR-V file must write");
            let words = to_u32_words(&spv);
            let array = words
                .iter()
                .map(|w| format!("0x{:08x}", w))
                .collect::<Vec<_>>()
                .join(", ");
            generated.push_str(&format!(
                "pub const {}_SPIRV: [u32; {}] = [{}];\n",
                name.to_uppercase(),
                words.len(),
                array
            ));
        }
        let generated_path = format!("{}/vulkan_spirv.rs", out_dir);
        fs::write(&generated_path, generated).expect(
            "the generated SPIR-V header must write",
        );
        println!("cargo:rustc-cfg=spirv_generated");
    } else {
        // The committed arrays are the build's input: the backend's
        // include! resolves through the spirv_fallback cfg (the build's
        // only fall-back path).
        println!("cargo:rustc-cfg=spirv_fallback");
    }
}

/// Finds glslangValidator on the PATH. The None result selects the
/// committed SPIR-V fallback. The candidate paths cover the common
/// homes, because the build script's process does not always carry the
/// user's full PATH.
fn find_validator() -> Option<String> {
    let candidates = [
        "glslangValidator",
        "/usr/bin/glslangValidator",
        "/usr/local/bin/glslangValidator",
        "/opt/homebrew/bin/glslangValidator",
    ];
    for candidate in candidates {
        if is_executable(candidate) {
            return Some(candidate.to_string());
        }
    }
    None
}

/// Whether the path is an executable file (the build's own test, no
/// third-party dependency).
fn is_executable(path: &str) -> bool {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        match fs::metadata(path) {
            Ok(meta) => {
                meta.is_file()
                    && meta.permissions().mode() & 0o111 != 0
            }
            Err(_) => false,
        }
    }
    #[cfg(not(unix))]
    {
        fs::metadata(path).map(|m| m.is_file()).unwrap_or(false)
    }
}

/// Extracts the shader bodies from the library. The library's constants
/// are named constant blocks whose value opens with a raw string; the
/// extraction is the build's own parse, not a general-purpose Rust parser.
fn extract_shaders(source: &str) -> Vec<(String, String)> {
    let mut shaders = Vec::new();
    let marker = ": &str = r\"";
    let mut rest = source;
    while let Some(pos) = rest.find(marker) {
        let before = &rest[..pos];
        let name = before
            .rsplit("pub const ")
            .next()
            .unwrap_or("")
            .trim()
            .to_string();
        let after = &rest[pos + marker.len()..];
        let body = match after.find("\";") {
            Some(end) => after[..end].to_string(),
            None => after.to_string(),
        };
        shaders.push((name, body));
        rest = after;
    }
    shaders
}

/// Compiles one shader to SPIR-V with glslangValidator. The validator is
/// the build's prerequisite; the build fails when the compile fails.
fn compile_shader(
    out_dir: &str,
    name: &str,
    body: &str,
    validator: &str,
) -> Vec<u8> {
    let stage = if name.ends_with("VERTEX_SHADER") {
        "vert"
    } else {
        "frag"
    };
    let source_path = format!("{}/{}.{}", out_dir, name, stage);
    fs::write(&source_path, body).expect("the shader source must write");
    let spv_path = format!("{}/{}.spv", out_dir, name);
    let output = Command::new(validator)
        .arg("-V")
        .arg(&source_path)
        .arg("-o")
        .arg(&spv_path)
        .output()
        .expect("glslangValidator must be runnable");
    if !output.status.success() {
        panic!(
            "glslangValidator failed for {}: {}",
            name,
            String::from_utf8_lossy(&output.stderr)
        );
    }
    fs::read(&spv_path).expect("the SPIR-V file must exist")
}

/// Splits the SPIR-V byte array into the engine's u32 words (the SPIR-V
/// words are little-endian).
fn to_u32_words(bytes: &[u8]) -> Vec<u32> {
    bytes
        .chunks_exact(4)
        .map(|c| {
            u32::from_le_bytes([c[0], c[1], c[2], c[3]])
        })
        .collect()
}
